/* اگر ممیز تایپ نشده بود: ۱۳۲ → ۱۳٫۲ ، ۱۲۶ → ۱۲٫۶ ، ۹۶ (استارت) → ۹٫۶ */
function dgFixDec(v, mode, t){
  if (!Number.isInteger(v)) return v;
  if (/[\d۰-۹]\s*[\/\u066B\u066C.,،·'’]\s*[\d۰-۹]/.test(t) || /دهم|صدم|ممیز|میلی/.test(t)) return v;
  if ((mode==='rest' || mode==='run' || mode===null) && v >= 80 && v <= 180) return v/10;
  if (mode==='crank' && v >= 30 && v <= 140) return v/10;
  return v;
}

function dgBox(title, speech, causes, tests, note){
  const col = /^🔴/.test(title) ? '#FF5C5C' : /^(🟠|🟡)/.test(title) ? '#FF9F1C' : /^(✅|🟢)/.test(title) ? '#3DDC84' : '#8AB4FF';
  const c = (causes || []).slice(0, 2), t = (tests || [])[0];
  let h = `<div class="causal" style="border-right:4px solid ${col};padding-right:10px"><div style="font-size:1.15em;font-weight:800;line-height:1.6">${dgEsc(title)}</div>`;
  if (c.length) h += `<div style="margin-top:6px">🔎 <b>مشکل از:</b> ${c.map(dgEsc).join(' ، ')}</div>`;
  if (t) h += `<div style="margin-top:4px">➡️ <b>بعدی:</b> ${dgEsc(t)}</div>`;
  if (note) h += `<div style="margin-top:4px">${note}</div>`;
  if ((causes && causes.length > 2) || (tests && tests.length > 1)){
    h += `<details style="margin-top:8px"><summary style="opacity:.8">همه‌ی مشکوک‌ها و تست‌ها</summary>`;
    if (causes && causes.length) h += `<div style="margin-top:6px"><b>مشکوک‌ها:</b><ol style="padding-right:18px;margin:4px 0">${causes.map(x=>`<li>${dgEsc(x)}</li>`).join('')}</ol></div>`;
    if (tests && tests.length) h += `<div><b>تست‌ها به ترتیب:</b><ol style="padding-right:18px;margin:4px 0">${tests.map(x=>`<li>${dgEsc(x)}</li>`).join('')}</ol></div>`;
    h += `</details>`;
  }
  h += `<div class="fixednote">محدوده‌ها برای باتری سربی ۱۲ ولتِ معمولی‌ان؛ برای هر ماشین، دفترچه‌ی همان ماشین مرجع است.</div></div>`;
  let sp = speech;
  if (c.length) sp += ' مشکوک: ' + c.join('، ') + '.';
  if (t) sp += ' بعدی: ' + t + '.';
  return {speech: sp, html: h};
}


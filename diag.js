function dgTopic(t){
  let best = null, bs = 0;
  for (const tp of DG_TOPICS){
    let s = 0;
    for (const k of tp.keys) if (k.test(t)) s++;
    if (s > bs){ bs = s; best = tp; }
  }
  if (!best) return null;
  DG_STATE.mode = best.expect; DG_STATE.num = null; DG_STATE.at = Date.now();
  const col = '#8AB4FF';
  let h = `<div class="causal" style="border-right:4px solid ${col};padding-right:10px"><div style="font-size:1.15em;font-weight:800;line-height:1.6">${best.title}</div>`;
  h += `<div style="margin-top:6px">➡️ <b>اول:</b> ${dgEsc(best.steps[0])}</div>`;
  if (best.steps.length > 1) h += `<details style="margin-top:8px"><summary style="opacity:.8">همه‌ی مراحل (${dgFa(best.steps.length)})</summary><ol style="padding-right:18px;margin:6px 0">${best.steps.map(x=>`<li>${dgEsc(x)}</li>`).join('')}</ol></details>`;
  if (best.expect) h += `<div class="fixednote">عددی که اندازه گرفتی را بگو تا تحلیل کنم؛ مثلاً «${best.expect==='rest'?'ماشین خاموشه، دوازده و چهار دهم':best.expect==='run'?'ماشین روشنه، سیزده و دو دهم':best.expect==='crank'?'حین استارت، هشت و پنج دهم':best.expect==='drop'?'افت ولتاژ روی منفی، یک ولت':best.expect==='leak'?'نشتی صد و بیست میلی‌آمپر':'نیم ولت'}».</div>`;
  h += `</div>`;
  return {speech: best.speech, html: h};
}

function quickAnswer(q){
  const t = String(q||'').replace(/ي/g,'ی').replace(/ك/g,'ک').replace(/\u200c/g,' ').replace(/ـ/g,'').toLowerCase().trim();
  const tokens = t.split(/\s+/).filter(Boolean);
  const fresh = Date.now() - DG_STATE.at < 120000;
  const volts = !/میلی|آمپر/.test(t);
  let v = dgNum(t, volts);
  let hasNum = v !== null && !isNaN(v);
  let mode = dgMode(t);
  const strong = /باتری|ولتاژ|ولت|دینام|آلترناتور|استارت|افت|نشتی|مصرف پنهان|میلی|ریپل|دیود|ای ?سی|\bac\b/.test(t);
  const restW = tokens.filter(w => !/^[\d۰-۹٫.\/,]+$/.test(w) && !Object.prototype.hasOwnProperty.call(DG_WORDS, w) && !['و','دهم','صدم','ممیز','ولت','ولتاژ','عدد','بود','است','شد','حدود','تقریبا','تقریباً'].includes(w));
  const negative = /نمی ?(?:شه|شود|زنه|زند|خوره|خورد|کنه|کند)|چرا|چطور|چگونه|چیکار|چی کار|چه کار/.test(t);

  /* ۱) فقط حالت گفته شد (مثلاً «ماشین روشنه») → عدد را بپرس، یا اگر عدد قبلاً گفته شده بود تحلیل کن */
  if (!hasNum && mode && tokens.length <= 4 && !negative){
    if (fresh && DG_STATE.num !== null){ v = DG_STATE.num; hasNum = true; }
    else {
      DG_STATE.mode = mode; DG_STATE.num = null; DG_STATE.at = Date.now();
      const sp = 'ولتاژ یا عددی که اندازه گرفتی چند بود؟';
      return {speech: sp, html: `<div class="causal"><b>حالت: ${mode==='rest'?'ماشین خاموش':mode==='run'?'ماشین روشن':mode==='crank'?'حین استارت':mode==='drop'?'افت ولتاژ':mode==='leak'?'مصرف پنهان':'ولت AC'}</b><br>عددی که اندازه گرفتی را بگو.</div>`};
    }
  }
  /* ۲) عدد بدون حالت، ولی تازه حالتی پرسیده شده بود */
  let pending = false;
  if (hasNum && !mode && fresh && DG_STATE.mode && restW.length <= 1 && !negative){ mode = DG_STATE.mode; pending = true; }

  if (hasNum && (mode || (!strong && tokens.length <= 4))) v = dgFixDec(v, mode, t);

  /* ۳) بدون عدد: سؤال مرجع یا راهنمای عیب‌یابی */
  if (!hasNum){
    if (/چقدر|چند|سالم|نرمال|استاندارد|درسته|باید باشه|محدوده/.test(t) && /ولتاژ|باتری|دینام|آلترناتور/.test(t) && !/افت|مصرف پنهان|نشتی/.test(t)){
      DG_STATE.mode = null; DG_STATE.at = Date.now();
      const sp = 'ماشین خاموش و چند ساعت بعد از توقف: ۱۲ و ۶ دهم تا ۱۲ و ۷ دهم ولت. زیر ۱۲ ولت یعنی خالی. ماشین روشن: ۱۳ و ۸ دهم تا ۱۴ و ۷ دهم. حین استارت: بالای ۹ و ۶ دهم. عددی که اندازه گرفتی را همراه حالتش بگو.';
      return {speech: sp, html: `<div class="causal"><b>📋 محدوده‌های سالم</b><ul style="padding-right:18px;margin:6px 0"><li>ماشین خاموش، چند ساعت بعد از توقف: ۱۲٫۶ تا ۱۲٫۷ (زیر ۱۲ یعنی خالی)</li><li>ماشین روشن (آلترناتور شارژ می‌کند): ۱۳٫۸ تا ۱۴٫۷</li><li>حین استارت: بالای ۹٫۶</li><li>افت ولتاژ: ارت تا ۰٫۱، مثبت تا حدود ۰٫۲</li><li>مصرف پنهان بعد از خواب ماژول‌ها: زیر ۵۰ میلی‌آمپر</li></ul>عددی که اندازه گرفتی را همراه حالتش بگو.<div class="fixednote">برای باتری سربی ۱۲ ولتِ معمولی؛ دفترچه‌ی هر ماشین مرجع است.</div></div>`};
    }
    return dgTopic(t);
  }

  /* ۳.۵) فقط یک عدد شبیه ولت گفته شد → حالتش را بپرس */
    if (hasNum && !mode && !pending && restW.length === 0 && v >= 8 && v <= 16 && !negative){
    DG_STATE.num = v; DG_STATE.mode = null; DG_STATE.at = Date.now();
    return {speech: 'عدد ' + dgSay(v) + ' را شنیدم. این مال کدوم حالته؟ بگو ماشین خاموش، ماشین روشن، یا حین استارت.',
      html: `<div class="causal"><b>عدد شنیده‌شده: ${dgShow(v)}</b><br>این مال کدوم حالته؟ بگو: «ماشین خاموش»، «ماشین روشن» یا «حین استارت».</div>`};
  }
  /* ۴) عدد دارد ولی ربطی به برق نداره («پژو ۴۰۵ روشن نمی‌شه») */
  if (!strong && !pending && !(mode && v >= 8 && v <= 16)) return dgTopic(t);

  /* ۵) عدد را با حالتش تحلیل کن */
  if (!mode && !(v >= 8 && v <= 16)) return dgTopic(t);
  if (!mode){
    DG_STATE.num = v; DG_STATE.mode = null; DG_STATE.at = Date.now();
    const sp = 'عدد ' + dgSay(v) + ' را شنیدم. این مال کدوم حالته؟ بگو ماشین خاموش، ماشین روشن، حین استارت، افت ولتاژ، یا مصرف پنهان.';
    return {speech: sp, html: `<div class="causal"><b>عدد شنیده‌شده: ${dgShow(v)}</b><br>این مال کدوم حالته؟ بگو: «ماشین خاموش»، «ماشین روشن»، «حین استارت»، «افت ولتاژ» یا «مصرف پنهان».</div>`};
  }
  DG_STATE.mode = null; DG_STATE.num = null; DG_STATE.at = 0;
  v = Math.round(v*100)/100;
  const f = dgShow;
  const r = dgJudge(mode, v, t, f);
  if (!r){
    if (/ولت|آمپر|دهم|ممیز|اهم/.test(t)) return {speech:'عدد غیرعادیه. دوباره بگو.', html:'عدد غیرعادیه؛ دوباره بگو. (اگه درست گفتی، مولتی‌متر یا اتصال‌ها را چک کن.)'};
    return dgTopic(t);
  }
  r.speech = 'شنیدم ' + dgSay(mode==='leak' && /آمپر/.test(t) && !/میلی/.test(t) && v < 5 ? v*1000 : v) + ' ' + DG_UNIT[mode] + '. ' + r.speech;
  return r;
}


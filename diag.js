function dgMode(t){
  if (/افت/.test(t)) return 'drop';
  if (/نشتی|نشت جریان|مصرف پنهان|مصرف خاموشی|میلی ?آمپر/.test(t)) return 'leak';
  if (/استارت|استارتر/.test(t)) return 'crank';
  if (/ریپل|ای ?سی|\bac\b|دیود/.test(t)) return 'ripple';
  if (/خاموش/.test(t)) return 'rest';
  if (/روشن|دینام|آلترناتور|دور موتور/.test(t)) return 'run';
  return null;
}
